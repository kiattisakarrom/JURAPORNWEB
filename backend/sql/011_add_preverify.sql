SET NOCOUNT ON;
SET XACT_ABORT ON;

IF OBJECT_ID(N'dbo.TBLPACKAGEPRESCRIPTIONS', N'U') IS NULL
  THROW 51000, 'dbo.TBLPACKAGEPRESCRIPTIONS is required before installing Pre Verify.', 1;
GO

IF COL_LENGTH(N'dbo.TBLPACKAGEPRESCRIPTIONS', N'PREVERIFY_SOURCE_REVISION') IS NULL
  ALTER TABLE dbo.TBLPACKAGEPRESCRIPTIONS ADD PREVERIFY_SOURCE_REVISION varchar(64) NULL;
GO
IF COL_LENGTH(N'dbo.TBLPACKAGEPRESCRIPTIONS', N'PREVERIFIED_AT') IS NULL
  ALTER TABLE dbo.TBLPACKAGEPRESCRIPTIONS ADD PREVERIFIED_AT datetime2(3) NULL;
GO
IF COL_LENGTH(N'dbo.TBLPACKAGEPRESCRIPTIONS', N'PREVERIFIED_BY') IS NULL
  ALTER TABLE dbo.TBLPACKAGEPRESCRIPTIONS ADD PREVERIFIED_BY nvarchar(150) NULL;
GO

PRINT 'Pre Verify columns are installed.';
GO
